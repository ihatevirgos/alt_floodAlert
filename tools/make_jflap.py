"""Generate docs/jflap/flood_alert_moore.jff from config/transitions.json.

Run from the repo root:  python tools/make_jflap.py

JFLAP input symbols use the single-character mapping from the proposal:
    L0=a  L1=b  L2=c  L3=d  R=r  D=s  T=t
Outputs use one letter each so the JFLAP output tape stays readable:
    MONITOR=M  ADVISE=A  SURGE=S  ALARM=L  SILENT=Q  FORCED=F  HOLD=H
Self-loops are written out, so every state has exactly one transition per
symbol (7 x 9 = 63 transitions). Re-run this after changing the table.
"""

import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SYMBOL_MAP = {"L0": "a", "L1": "b", "L2": "c", "L3": "d", "R": "r", "D": "s", "T": "t"}
OUTPUT_MAP = {"MONITOR": "M", "ADVISE": "A", "SURGE": "S", "ALARM": "L", "SILENT": "Q", "FORCED": "F", "HOLD": "H"}

# Layout roughly following Figure 2 of the proposal.
POSITIONS = {
    "Normal": (120, 100), "Prep": (380, 100), "PrepClear": (640, 100),
    "Surge": (120, 300), "Evac": (380, 300), "Forced": (640, 300),
    "Silenced": (380, 470), "Clearing": (120, 620), "Recovery": (380, 620),
}


def main() -> None:
    tr = json.loads((ROOT / "config/transitions.json").read_text(encoding="utf-8"))
    out = json.loads((ROOT / "config/outputs.json").read_text(encoding="utf-8"))
    states, delta, lam = tr["states"], tr["delta"], out["lambda"]
    ids = {q: i for i, q in enumerate(states)}

    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
        "<!--Generated by tools/make_jflap.py from config/transitions.json. Do not edit by hand.-->",
        "<structure>",
        "\t<type>moore</type>",
        "\t<automaton>",
    ]
    for q in states:
        x, y = POSITIONS.get(q, (100 + 120 * ids[q], 800))
        initial = "\t\t\t<initial/>\n" if q == tr["initial_state"] else ""
        lines.append(
            f'\t\t<state id="{ids[q]}" name="{escape(q)}">\n'
            f"\t\t\t<x>{x:.1f}</x>\n\t\t\t<y>{y:.1f}</y>\n{initial}"
            f"\t\t\t<output>{OUTPUT_MAP[lam[q]]}</output>\n\t\t</state>"
        )
    for q in states:
        for sym in tr["alphabet"]:
            target = delta[q][sym]
            lines.append(
                "\t\t<transition>\n"
                f"\t\t\t<from>{ids[q]}</from>\n\t\t\t<to>{ids[target]}</to>\n"
                f"\t\t\t<read>{SYMBOL_MAP[sym]}</read>\n"
                f"\t\t\t<transout>{OUTPUT_MAP[lam[target]]}</transout>\n"
                "\t\t</transition>"
            )
    lines += ["\t</automaton>", "</structure>", ""]

    dest = ROOT / "docs/jflap/flood_alert_moore.jff"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines), encoding="utf-8")
    n = len(states) * len(tr["alphabet"])
    print(f"Wrote {dest.relative_to(ROOT)} ({len(states)} states, {n} transitions)")
    sample = "s a b r t b c d c b s s"
    print(f"Sample run input for JFLAP (proposal Table, no spaces): {sample.replace(' ', '')}")


if __name__ == "__main__":
    main()
